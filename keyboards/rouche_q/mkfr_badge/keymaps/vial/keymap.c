static uint8_t last_key = 0;
static bool a_down = false;
static bool b_down = false;

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) last_key = keycode;
    if (keycode == KC_1) a_down = record->event.pressed;
    if (keycode == KC_2) b_down = record->event.pressed;
    return true;
}

