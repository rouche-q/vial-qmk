bool oled_task_user(void) {
    if (a_down && b_down) {
        oled_write_raw_P(kuruje_logo, sizeof(kuruje_logo));
        return false;
    }

    switch (last_key) {
        case KC_1:
            oled_write_raw_P(putain_logo, sizeof(putain_logo));
            break;

        case KC_2:
            oled_write_raw_P(cheh_logo, sizeof(cheh_logo));
            break;

        default:
            oled_write_raw_P(kuruje_logo, sizeof(kuruje_logo));
            break;
    }

    return false;
}

